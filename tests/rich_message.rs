#[test]
fn rich_doc_serializes_headings_tables_details_list_and_buttons() {
    let dt = RichSpan::date_time("21 Nov 2026", 1_795_200_000, "Dt").unwrap();
    let doc = RichDoc::new()
        .heading(HeadingLevel::H2, RichSpan::bold("Market Digest"))
        .paragraph(RichSpan::concat([
            RichSpan::plain("Updated: "),
            dt,
            RichSpan::plain(" · "),
            RichSpan::code("BTC/USD"),
            RichSpan::plain(" · "),
            RichSpan::url("Docs", "https://example.invalid/docs"),
        ]))
        .table(
            RichTable::new()
                .bordered(true)
                .striped(true)
                .compact(true)
                .caption("Spot Rates")
                .header_row(["Asset", "Price"])
                .row([
                    RichTableCell::new(RichSpan::bold("BTC")).align(TextAlign::Left),
                    RichTableCell::new("$95,000")
                        .align(TextAlign::Right)
                        .valign(VerticalAlign::Bottom),
                ]),
        )
        .details(
            "Checklist",
            true,
            RichDoc::new().list(
                RichList::new()
                    .checkbox("Sync rates", true)
                    .checkbox("Publish report", false),
            ),
        )
        .buttons(
            [
                RichButton::callback("Refresh", "refresh:btc").style(ButtonStyle::Primary),
                RichButton::copy_text("Copy", "95000").style(ButtonStyle::Success),
                RichButton::url("Open", "https://example.invalid").style(ButtonStyle::Danger),
                RichButton::callback("Reset", "reset:btc")
                    .style(ButtonStyle::Primary)
                    .style(ButtonStyle::Default),
            ],
            Some(TextAlign::Center),
        )
        .divider()
        .footer("Generated by GramRelay")
        .build()
        .unwrap();

    let value: Value = serde_json::to_value(&doc).unwrap();
    let blocks = value["blocks"].as_array().unwrap();
    assert_eq!(blocks.len(), 7);

    assert_eq!(blocks[0]["type"], "heading");
    assert_eq!(blocks[0]["size"], 2);
    assert_eq!(blocks[0]["text"]["type"], "bold");
    assert_eq!(blocks[0]["text"]["text"], "Market Digest");

    assert_eq!(blocks[1]["type"], "paragraph");
    assert_eq!(blocks[1]["text"][1]["type"], "date_time");
    assert_eq!(blocks[1]["text"][1]["date_time_format"], "Dt");

    assert_eq!(blocks[2]["type"], "table");
    assert_eq!(blocks[2]["is_bordered"], true);
    assert_eq!(blocks[2]["is_striped"], true);
    assert_eq!(blocks[2]["is_compact"], true);
    assert_eq!(blocks[2]["caption"], "Spot Rates");
    assert_eq!(blocks[2]["cells"][0][0]["is_header"], true);
    assert_eq!(blocks[2]["cells"][0][0]["align"], "left");
    assert_eq!(blocks[2]["cells"][0][0]["valign"], "middle");
    assert_eq!(blocks[2]["cells"][1][1]["align"], "right");
    assert_eq!(blocks[2]["cells"][1][1]["valign"], "bottom");

    assert_eq!(blocks[3]["type"], "details");
    assert_eq!(blocks[3]["is_open"], true);
    assert_eq!(blocks[3]["blocks"][0]["type"], "list");
    assert_eq!(blocks[3]["blocks"][0]["items"][0]["has_checkbox"], true);
    assert_eq!(blocks[3]["blocks"][0]["items"][0]["is_checked"], true);
    assert_eq!(blocks[3]["blocks"][0]["items"][1]["has_checkbox"], true);
    assert!(
        blocks[3]["blocks"][0]["items"][1]
            .get("is_checked")
            .is_none()
    );

    assert_eq!(blocks[4]["type"], "buttons");
    assert_eq!(blocks[4]["align"], "center");
    assert_eq!(blocks[4]["buttons"][0]["style"], "primary");
    assert_eq!(blocks[4]["buttons"][0]["callback_data"], "refresh:btc");
    assert_eq!(blocks[4]["buttons"][1]["style"], "success");
    assert_eq!(blocks[4]["buttons"][1]["copy_text"]["text"], "95000");
    assert_eq!(blocks[4]["buttons"][2]["style"], "danger");
    assert_eq!(blocks[4]["buttons"][2]["url"], "https://example.invalid");
    assert!(blocks[4]["buttons"][3].get("style").is_none());
    assert_eq!(blocks[4]["buttons"][3]["callback_data"], "reset:btc");

    assert_eq!(blocks[5]["type"], "divider");
    assert_eq!(blocks[6]["type"], "footer");
    assert_eq!(blocks[6]["text"], "Generated by GramRelay");
}

#[test]
fn rich_span_date_time_validates_telegram_grammar() {
    for valid in ["", "r", "w", "d", "D", "t", "T", "wdT", "wDt", "Dt", "dt"] {
        let span = RichSpan::date_time("now", 1_700_000_000, valid).unwrap();
        let wire: WireRichText = span.into_wire();
        let json = serde_json::to_value(wire).unwrap();
        assert_eq!(json["type"], "date_time");
        assert_eq!(json["date_time_format"], valid);
    }

    for invalid in ["rw", "td", "dD", "tT", "x", "ww", "Dt "] {
        let error = RichSpan::date_time("now", 1_700_000_000, invalid).unwrap_err();
        assert_eq!(error.kind(), ErrorKind::Validation);
        assert_eq!(error.outcome(), EffectOutcome::NotSent);
        assert_eq!(error.field(), Some("date_time_format"));
    }
}

#[tokio::test]
async fn rich_doc_photo_attach_integrates_with_send_rich_message_multipart() {
    let server = MockServer::start().await;
    Mock::given(method("POST"))
        .respond_with(ResponseTemplate::new(200).set_body_json(json!({
            "ok": true,
            "result": {"message_id": 42, "date": 1, "chat": {"id": 1, "type": "private"}}
        })))
        .expect(1)
        .mount(&server)
        .await;

    let bot = Bot::builder(TOKEN)
        .api_url(server.uri())
        .allow_http_loopback(true)
        .build()
        .unwrap();

    let doc = RichDoc::new()
        .heading(HeadingLevel::H3, "Chart")
        .photo_attach("chart", Some(RichSpan::italic("24h candles")))
        .build()
        .unwrap();

    let sent = bot
        .api()
        .send_rich_message(doc)
        .chat_id(ChatId::from(1).into())
        .attach(
            "chart",
            InputFile::bytes("chart.png", vec![137, 80, 78, 71]),
        )
        .await
        .unwrap();
    assert_eq!(i64::from(sent.message_id), 42);

    let requests = server.received_requests().await.unwrap();
    let body = String::from_utf8_lossy(&requests[0].body);
    assert!(body.contains("attach://chart"));
    assert!(body.contains("name=\"chart\"; filename=\"chart.png\""));
    assert!(
        requests[0]
            .body
            .windows(4)
            .any(|bytes| bytes == [137, 80, 78, 71])
    );
}

#[test]
fn entity_text_alias_coexists_cleanly_with_wire_rich_text() {
    let entity_text =
        EntityText::new("Hello ").append(EntityText::styled("world", EntityKind::Bold).unwrap());
    let wire_text: WireRichText = RichSpan::bold("world").into();

    assert_eq!(entity_text.text(), "Hello world");
    assert_eq!(entity_text.entities().len(), 1);
    assert_eq!(
        serde_json::to_value(wire_text).unwrap(),
        json!({"type": "bold", "text": "world"})
    );
}

#[test]
fn rich_doc_validates_button_limits_text_and_callback_boundaries() {
    let eight: Vec<RichButton> = (0..8)
        .map(|idx| RichButton::callback(format!("B{idx}"), "a".repeat(64)))
        .collect();
    let msg = RichDoc::new().buttons(eight, None).build().unwrap();
    assert!(msg.blocks.is_some());

    let nine: Vec<RichButton> = (0..9)
        .map(|idx| RichButton::callback(format!("B{idx}"), format!("cb:{idx}")))
        .collect();
    let err = RichDoc::new().buttons(nine, None).build().unwrap_err();
    assert_eq!(err.kind(), ErrorKind::Validation);
    assert_eq!(err.outcome(), EffectOutcome::NotSent);
    assert_eq!(err.field(), Some("rich_buttons"));

    let empty_row: Vec<RichButton> = Vec::new();
    let err = RichDoc::new().buttons(empty_row, None).build().unwrap_err();
    assert_eq!(err.field(), Some("rich_buttons"));

    let err = RichDoc::new()
        .buttons([RichButton::callback("TooLong", "a".repeat(65))], None)
        .build()
        .unwrap_err();
    assert_eq!(err.field(), Some("callback_data"));

    let err = RichDoc::new()
        .buttons([RichButton::callback("Empty", "")], None)
        .build()
        .unwrap_err();
    assert_eq!(err.field(), Some("callback_data"));

    let err = RichDoc::new()
        .buttons([RichButton::callback(RichSpan::bold("Bold"), "ok")], None)
        .build()
        .unwrap_err();
    assert_eq!(err.field(), Some("button_text"));

    let emoji_label = RichSpan::concat([
        RichSpan::custom_emoji("5429651785352501917", "🔥"),
        RichSpan::plain(" Go"),
    ]);
    assert!(
        RichDoc::new()
            .buttons([RichButton::callback(emoji_label, "ok")], None)
            .build()
            .is_ok()
    );
}

#[test]
fn rich_doc_validates_attachments_tables_and_nested_sections() {
    let err = RichDoc::new().build().unwrap_err();
    assert_eq!(err.field(), Some("rich_blocks"));

    let err = RichDoc::new()
        .photo_attach("attach://chart", None)
        .build()
        .unwrap_err();
    assert_eq!(err.field(), Some("attachment_name"));

    let err = RichDoc::new().photo_attach("", None).build().unwrap_err();
    assert_eq!(err.field(), Some("attachment_name"));

    let err = RichDoc::new()
        .table(RichTable::new().row([RichTableCell::new("Bad").colspan(0)]))
        .build()
        .unwrap_err();
    assert_eq!(err.field(), Some("colspan"));

    let err = RichDoc::new()
        .table(RichTable::new().row([RichTableCell::new("Bad").rowspan(-1)]))
        .build()
        .unwrap_err();
    assert_eq!(err.field(), Some("rowspan"));

    let nested_bad = RichDoc::new().details(
        "Section",
        false,
        RichDoc::new().buttons([RichButton::callback(RichSpan::italic("Bad"), "x")], None),
    );
    let err = tg::api::types::InputRichMessage::try_from(nested_bad).unwrap_err();
    assert_eq!(err.kind(), ErrorKind::Validation);
    assert_eq!(err.outcome(), EffectOutcome::NotSent);
    assert_eq!(err.field(), Some("button_text"));
}

#[cfg(feature = "bot")]
#[tokio::test]
async fn context_reply_rich_preserves_delivery_scope_and_attachments() {
    let server = MockServer::start().await;
    Mock::given(method("POST"))
        .respond_with(ResponseTemplate::new(200).set_body_json(json!({
            "ok": true,
            "result": {"message_id": 99, "date": 1, "chat": {"id": -100123, "type": "supergroup"}}
        })))
        .expect(2)
        .mount(&server)
        .await;

    let bot = Bot::builder(TOKEN)
        .api_url(server.uri())
        .allow_http_loopback(true)
        .build()
        .unwrap();

    let router = tg::Router::new()
        .command("report", |ctx: tg::MessageContext| async move {
            ctx.reply_rich(
                RichDoc::new()
                    .heading(HeadingLevel::H2, "Summary")
                    .photo_attach("chart", Some(RichSpan::plain("24h"))),
            )
            .attach("chart", InputFile::bytes("chart.png", vec![1, 2, 3, 4]))
            .await?;
            Ok(())
        })
        .callback("ephem", |ctx: tg::CallbackContext| async move {
            ctx.ephemeral_reply_rich(RichDoc::new().paragraph("Only for caller"))?
                .await?;
            Ok(())
        });

    let msg_update: tg::Update = serde_json::from_value(json!({
        "update_id": 1,
        "message": {
            "message_id": 77,
            "date": 1,
            "chat": {"id": -100123, "type": "supergroup"},
            "text": "/report",
            "message_thread_id": 12,
            "business_connection_id": "biz-1"
        }
    }))
    .unwrap();
    router.dispatch(&bot, msg_update).await.unwrap();

    let cb_update: tg::Update = serde_json::from_value(json!({
        "update_id": 2,
        "callback_query": {
            "id": "cb-1",
            "from": {"id": 5, "is_bot": false, "first_name": "Ada"},
            "chat_instance": "inst",
            "data": "ephem"
        }
    }))
    .unwrap();
    router.dispatch(&bot, cb_update).await.unwrap();

    let requests = server.received_requests().await.unwrap();
    assert_eq!(requests.len(), 2);

    let multipart_body = String::from_utf8_lossy(&requests[0].body);
    assert!(multipart_body.contains("name=\"chat_id\"\r\n\r\n-100123"));
    assert!(multipart_body.contains("name=\"message_thread_id\"\r\n\r\n12"));
    assert!(multipart_body.contains("name=\"business_connection_id\"\r\n\r\nbiz-1"));
    assert!(multipart_body.contains("attach://chart"));
    assert!(multipart_body.contains("name=\"chart\"; filename=\"chart.png\""));

    let ephem_body: Value = serde_json::from_slice(&requests[1].body).unwrap();
    assert_eq!(
        ephem_body["ephemeral_message_parameters"]["callback_query_id"],
        "cb-1"
    );
    assert_eq!(
        ephem_body["rich_message"]["blocks"][0]["text"],
        "Only for caller"
    );
}

#[cfg(feature = "bot")]
#[tokio::test]
async fn context_reply_rich_rejects_guest_messages_locally() {
    let server = MockServer::start().await;
    let bot = Bot::builder(TOKEN)
        .api_url(server.uri())
        .allow_http_loopback(true)
        .build()
        .unwrap();

    let router = tg::Router::new().on_message_event(
        tg::MessageEvent::GuestMessage,
        |ctx: tg::MessageContext| async move {
            let err = ctx
                .reply_rich(RichDoc::new().paragraph("Blocked"))
                .await
                .unwrap_err();
            assert_eq!(err.kind(), ErrorKind::Validation);
            assert_eq!(err.outcome(), EffectOutcome::NotSent);
            assert_eq!(err.field(), Some("guest_query_id"));
            Ok(())
        },
    );

    let guest_update: tg::Update = serde_json::from_value(json!({
        "update_id": 3,
        "guest_message": {
            "message_id": 10,
            "date": 1,
            "chat": {"id": 99, "type": "private"},
            "text": "hi",
            "guest_query_id": "gq-1"
        }
    }))
    .unwrap();
    router.dispatch(&bot, guest_update).await.unwrap();
    assert!(server.received_requests().await.unwrap().is_empty());
}
