CREATE TABLE mtproto_update_feeds (
    profile TEXT NOT NULL PRIMARY KEY REFERENCES account_profiles(profile),
    retention_ms INTEGER NOT NULL CHECK(retention_ms > 0),
    max_event_bytes INTEGER NOT NULL CHECK(max_event_bytes > 0),
    max_batch_bytes INTEGER NOT NULL CHECK(max_batch_bytes >= max_event_bytes),
    last_sequence INTEGER NOT NULL DEFAULT 0 CHECK(last_sequence >= 0),
    floor_sequence INTEGER NOT NULL DEFAULT 0 CHECK(floor_sequence >= 0 AND floor_sequence <= last_sequence),
    last_received_at_ms INTEGER NOT NULL DEFAULT 0,
    entry_count INTEGER NOT NULL DEFAULT 0 CHECK(entry_count >= 0),
    byte_count INTEGER NOT NULL DEFAULT 0 CHECK(byte_count >= 0),
    source_id BLOB CHECK(length(source_id) = 32),
    source_worker TEXT,
    source_revision INTEGER NOT NULL DEFAULT 0 CHECK(source_revision >= 0),
    source_until_ms INTEGER,
    last_ordinal BLOB CHECK(length(last_ordinal) = 8),
    last_id BLOB CHECK(length(last_id) = 32),
    last_hash BLOB CHECK(length(last_hash) = 32),
    last_kind TEXT CHECK(last_kind IN ('baseline','events','resync','gap')),
    last_start INTEGER CHECK(last_start > 0),
    last_end INTEGER CHECK(last_end >= last_start AND last_end <= last_sequence),
    CHECK((source_worker IS NULL) = (source_until_ms IS NULL)),
    CHECK((last_ordinal IS NULL) = (last_id IS NULL)),
    CHECK((last_ordinal IS NULL) = (last_hash IS NULL)),
    CHECK((last_ordinal IS NULL) = (last_kind IS NULL)),
    CHECK((last_ordinal IS NULL) = (last_start IS NULL)),
    CHECK((last_ordinal IS NULL) = (last_end IS NULL)),
    CHECK(last_ordinal IS NULL OR source_id IS NOT NULL)
) STRICT;
CREATE TABLE mtproto_updates (
    profile TEXT NOT NULL REFERENCES mtproto_update_feeds(profile),
    sequence INTEGER NOT NULL CHECK(sequence > 0),
    source_id BLOB NOT NULL CHECK(length(source_id) = 32),
    ordinal BLOB CHECK(length(ordinal) = 8),
    batch_id BLOB CHECK(length(batch_id) = 32),
    batch_kind TEXT NOT NULL CHECK(batch_kind IN ('baseline','events','resync','gap','source_change')),
    payload BLOB NOT NULL,
    payload_hash BLOB NOT NULL CHECK(length(payload_hash) = 32),
    callback_query BLOB CHECK(length(callback_query) = 8),
    byte_size INTEGER NOT NULL CHECK(byte_size = length(payload) + COALESCE(length(callback_query),0)),
    checkpoint_acknowledged INTEGER NOT NULL DEFAULT 0 CHECK(checkpoint_acknowledged IN (0,1)),
    received_at_ms INTEGER NOT NULL,
    expires_at_ms INTEGER NOT NULL,
    PRIMARY KEY(profile,sequence),
    CHECK((ordinal IS NULL) = (batch_id IS NULL)),
    CHECK((ordinal IS NULL) = (batch_kind = 'source_change')),
    CHECK(checkpoint_acknowledged = 0 OR batch_kind IN ('baseline','events','resync'))
) STRICT;
CREATE INDEX mtproto_updates_retention ON mtproto_updates(expires_at_ms,profile,sequence);
